-- VITRA: estrutura isolada de usuários e auditoria.
-- Aplicar SOMENTE em um projeto Supabase exclusivo do VITRA.
-- Nenhuma tabela do NEXO deve ser utilizada.
create table if not exists public.vitra_access_users (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  display_name text not null,
  auth_email text not null unique,
  role text not null default 'member' check (role in ('master','member')),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  last_login_at timestamptz,
  constraint vitra_username_format check (username ~ '^[a-z0-9._-]{3,32}$'),
  constraint vitra_display_name_not_blank check (length(btrim(display_name)) between 2 and 80)
);
create unique index if not exists vitra_exactly_one_master
  on public.vitra_access_users (role) where role = 'master';

create table if not exists public.vitra_access_events (
  id bigint generated by default as identity primary key,
  user_id uuid,
  username text not null,
  event text not null check (event in
    ('login','logout','create_user','update_user','reset_password',
     'block_user','unblock_user','delete_user')),
  occurred_at timestamptz not null default now(),
  actor_id uuid,
  details text
);
create index if not exists vitra_events_recent on public.vitra_access_events (occurred_at desc);
create index if not exists vitra_events_user on public.vitra_access_events (user_id, occurred_at desc);

-- Token de configuração inicial: nunca armazenar o token original.
-- Inserir hash SHA-256 de um código aleatório de 32+ bytes ANTES de liberar o bootstrap.
create table if not exists public.vitra_auth_setup (
  id boolean primary key default true check (id = true),
  secret_hash text not null check (secret_hash ~ '^[a-f0-9]{64}$'),
  used_at timestamptz,
  created_at timestamptz not null default now()
);
-- Tentativas limitadas pela função; sem endereço IP em claro.
create table if not exists public.vitra_login_attempts (
  id bigint generated by default as identity primary key,
  fingerprint text not null,
  attempted_at timestamptz not null default now()
);
create index if not exists vitra_login_attempts_recent
  on public.vitra_login_attempts(fingerprint, attempted_at desc);

alter table public.vitra_access_users enable row level security;
alter table public.vitra_access_events enable row level security;
alter table public.vitra_auth_setup enable row level security;
alter table public.vitra_login_attempts enable row level security;

-- Acesso apenas do serviço privilegiado (Edge Function). Nenhuma permissão direta
-- ao navegador, independentemente de possuir uma sessão Auth válida.
revoke all on public.vitra_access_users from anon, authenticated, public;
revoke all on public.vitra_access_events from anon, authenticated, public;
revoke all on public.vitra_auth_setup from anon, authenticated, public;
revoke all on public.vitra_login_attempts from anon, authenticated, public;
revoke all on sequence public.vitra_access_events_id_seq from anon, authenticated, public;
revoke all on sequence public.vitra_login_attempts_id_seq from anon, authenticated, public;